/// Jieli RCSP auth crypto — the handshake cipher for AuraCast-family badges
/// (E87/L8). Ported 1:1 from AuraCast's `jl-auth.ts` (MIT © Felix Herbst),
/// itself reverse-engineered from `libjl_auth.so`. Verified byte-exact against
/// the TypeScript with a Python reference (see `selfTest()`).
///
/// Handshake (all RAW writes on the AE01 characteristic; replies arrive on AE02):
///   TX [0x00, rand×16]  →  RX [0x01, enc×16]
///   TX [0x02,"pass"]     →  RX [0x00, challenge×16]
///   TX getEncryptedAuthData(challenge) = [0x01, enc×16]  →  RX [0x02,"pass"] ✓
enum JieliAuth {
    private static let mask = 0x9999
    private static let m32 = 0xFFFFFFFF

    // MARK: - Public API

    /// [0x00, rand×16] — the auth init packet.
    static func randomAuthData() -> [UInt8] {
        var out: [UInt8] = [0x00]
        out.append(contentsOf: (0..<16).map { _ in UInt8.random(in: 0...255) })
        return out
    }

    /// Encrypt a device challenge [0x00, challenge×16] → [0x01, enc×16].
    static func encryptedAuthData(_ challenge17: [UInt8]) -> [UInt8] {
        let input16 = (1...16).map { Int(challenge17[$0]) }
        let enc = functionE1test(key6: magic, input16: input16, seed16: staticKey)
        return [0x01] + enc.map { UInt8($0 & 0xFF) }
    }

    /// Sanity check against the known test vector. Call once at startup if you
    /// want to be sure the port is intact on-device.
    static func selfTest() -> Bool {
        let challenge = [UInt8]([0x00] + (1...16).map { UInt8($0) })
        let expected: [UInt8] = [0x01, 0x65, 0x5D, 0x48, 0x68, 0x6E, 0x41, 0x8C, 0xF7,
                                 0x1F, 0x25, 0xFB, 0xC5, 0xCB, 0xEF, 0xFA, 0x77]
        return encryptedAuthData(challenge) == expected
    }

    // MARK: - Core cipher (ported from jl-auth.ts)

    private static func keySchedule(_ d: [Int]) -> [Int] {
        var out = [Int](repeating: 0, count: 272)
        for i in 0..<16 { out[i] = d[i] }
        var buf = Array(d[0..<16])
        var checksum = 0
        for b in d { checksum ^= b }
        buf.append(checksum & 0xFF)
        for rnd in 0..<16 {
            for i in 0..<17 {
                let b = buf[i]
                buf[i] = ((b << 3) | (b >> 5)) & 0xFF
            }
            var readPos = (rnd + 1) % 17
            for j in 0..<16 {
                let src = buf[readPos]
                let tblIdx = 0xF + rnd * 16 - j
                out[16 + rnd * 16 + j] = (ksTable[tblIdx] + src) & 0xFF
                readPos += 1
                if readPos > 16 { readPos = 0 }
            }
        }
        return out
    }

