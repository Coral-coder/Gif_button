    private static func condMix(_ state: [Int], _ keyBlock: [Int], _ mask: Int, _ phase: Int) -> [Int] {
        var result = state
        for i in 0..<16 {
            let bitSet = ((1 << i) & mask) != 0
            if phase == 3 {
                result[i] = bitSet ? (result[i] ^ keyBlock[i]) : ((keyBlock[i] + result[i]) & 0xFF)
            } else {
                result[i] = bitSet ? ((keyBlock[i] + result[i]) & 0xFF) : (result[i] ^ keyBlock[i])
            }
        }
        return result
    }

    private static func sboxSub(_ state: [Int]) -> [Int] {
        var result = state
        for pos in [0, 3, 4, 7, 8, 11, 12, 15] { result[pos] = sbox[result[pos]] }
        for pos in [1, 2, 5, 6, 9, 10, 13, 14] { result[pos] = isbox[result[pos]] }
        return result
    }

    private static func blockCipher(_ stateIn: [Int], _ ek: [Int], _ mode: Int) -> [Int] {
        var s = stateIn
        let initial = stateIn
        s = condMix(s, Array(ek[0..<16]), mask, 3)
        s = sboxSub(s)
        s = condMix(s, Array(ek[16..<32]), mask, 5)

        var x9 = 1
        while x9 <= 8 {
            s = fibonacciMix(s)
            let ekOff = x9 * 0x20
            if x9 == 8 {
                s = condMix(s, Array(ek[0x100..<0x110]), mask, 3)
                break
            }
            if mode != 0 && x9 == 2 {
                for i in 0..<16 {
                    let bitSet = ((1 << i) & mask) != 0
                    s[i] = bitSet ? (s[i] ^ initial[i]) : ((initial[i] + s[i]) & 0xFF)
                }
            }
            s = condMix(s, Array(ek[ekOff..<ekOff + 16]), mask, 3)
            s = sboxSub(s)
            s = condMix(s, Array(ek[ekOff + 16..<ekOff + 32]), mask, 5)
            x9 += 1
        }
        return s
    }

    private static func functionE1test(key6: [Int], input16: [Int], seed16: [Int]) -> [Int] {
        let expandedKey = (0..<16).map { key6[$0 % 6] }
        var output = Array(input16[0..<16])

        let ks1 = keySchedule(Array(seed16[0..<16]))
        var cipherOut = blockCipher(output, ks1, 0)
        for i in 0..<16 { cipherOut[i] = (expandedKey[i] + (cipherOut[i] ^ input16[i])) & 0xFF }

        let obf = [
            (seed16[0]  - 0x17) & 0xFF, (seed16[1]  ^ 0xE5),
            (seed16[2]  - 0x21) & 0xFF, (seed16[3]  ^ 0xC1),
            (seed16[4]  - 0x4D) & 0xFF, (seed16[5]  ^ 0xA7),
            (seed16[6]  - 0x6B) & 0xFF, (seed16[7]  ^ 0x83),
            (seed16[8]  ^ 0xE9),        (seed16[9]  - 0x1B) & 0xFF,
            (seed16[10] ^ 0xDF),        (seed16[11] - 0x3F) & 0xFF,
            (seed16[12] ^ 0xB3),        (seed16[13] - 0x59) & 0xFF,
            (seed16[14] ^ 0x95),        (seed16[15] - 0x7D) & 0xFF,
        ]
        let ks2 = keySchedule(obf)
        output = blockCipher(cipherOut, ks2, 1)
        return output
    }

